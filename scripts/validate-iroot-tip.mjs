import {chromium} from 'playwright';
import {mkdir,writeFile} from 'node:fs/promises';
const output=process.env.TIP_OUTPUT || 'output/playwright/iroot-tip';
const base=process.env.TIP_BASE_URL || 'http://127.0.0.1:4338';
await mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true,channel:'chrome',args:['--use-angle=d3d11','--enable-gpu']});
const context=await browser.newContext({viewport:{width:1440,height:1000},deviceScaleFactor:1,reducedMotion:'no-preference'});
const page=await context.newPage();
const errors=[];
page.on('pageerror',error=>errors.push(error.stack));
await page.goto(base + '/products/iroot-sp-disposable-tips/',{waitUntil:'networkidle'});
await page.locator('[data-tip-card]').scrollIntoViewIfNeeded();
await page.locator('[data-tip-closeup][data-ready="true"]').waitFor();
await page.mouse.move(10,10);
const range=await page.locator('[data-tip-scroll]').evaluate(section=>{
  const card=section.querySelector('[data-tip-card]');
  const inset=parseFloat(getComputedStyle(card).top)||24;
  return {start:section.getBoundingClientRect().top+scrollY-inset,travel:section.offsetHeight-card.offsetHeight};
});
const samples=[];
for(const fraction of [0,.25,.5,.75,1]){
  await page.evaluate(y=>window.scrollTo({top:y,behavior:'instant'}),range.start+range.travel*fraction);
  await page.waitForFunction(expected=>Math.abs(Number(document.querySelector('[data-tip-closeup]').dataset.displayDegrees)-expected)<1.5,fraction*360);
  const sample=await page.locator('[data-tip-scroll]').evaluate(section=>({scrollDegrees:Number(section.dataset.scrollDegrees),displayDegrees:Number(section.querySelector('[data-tip-closeup]').dataset.displayDegrees),scrollY}));
  samples.push(sample);
  await page.locator('[data-tip-card]').screenshot({path:`${output}/tip-${fraction*360}.png`});
}
await page.evaluate(y=>window.scrollTo({top:y,behavior:'instant'}),range.start+range.travel*.25);
await page.waitForFunction(()=>Math.abs(Number(document.querySelector('[data-tip-closeup]').dataset.displayDegrees)-90)<1.5);
const beforeHover=Number(await page.locator('[data-tip-closeup]').getAttribute('data-display-degrees'));
await page.locator('[data-tip-closeup] canvas').hover();
await page.waitForFunction(before=>Number(document.querySelector('[data-tip-closeup]').dataset.displayDegrees)>before+20,beforeHover);
const afterHover=Number(await page.locator('[data-tip-closeup]').getAttribute('data-display-degrees'));
await page.mouse.move(10,10);
const beforeWheel=await page.evaluate(()=>scrollY);
await page.locator('[data-tip-closeup] canvas').hover();
await page.mouse.wheel(0,220);
await page.waitForFunction(before=>scrollY>before+100,beforeWheel);
const afterWheel=await page.evaluate(()=>scrollY);
await page.setViewportSize({width:390,height:844});
await page.reload({waitUntil:'networkidle'});
await page.locator('[data-tip-card]').scrollIntoViewIfNeeded();
await page.locator('[data-tip-closeup][data-ready="true"]').waitFor();
await page.locator('[data-tip-card]').screenshot({path:output+'/tip-mobile.png'});
const mobileOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
await page.emulateMedia({reducedMotion:'reduce'});
await page.waitForFunction(()=>document.querySelector('[data-tip-closeup]').dataset.reducedMotion==='true');
await page.locator('[data-tip-closeup] canvas').focus();
const keyboardBefore=Number(await page.locator('[data-tip-closeup]').getAttribute('data-display-degrees'));
await page.keyboard.press('ArrowRight');
await page.waitForFunction(before=>Number(document.querySelector('[data-tip-closeup]').dataset.displayDegrees)>before+15,keyboardBefore);
const keyboardAfter=Number(await page.locator('[data-tip-closeup]').getAttribute('data-display-degrees'));
const state=await page.locator('[data-tip-closeup]').evaluate(stage=>({...stage.dataset}));
if(samples[4].scrollDegrees<359||samples[4].displayDegrees<358)throw new Error('Full rotation not completed');
const headerInFlow=await page.locator('header.compact-product-header').evaluate(header=>!['sticky','fixed'].includes(getComputedStyle(header).position));
if(!headerInFlow)throw new Error('Header can cover the mobile tip card');
if(mobileOverflow||errors.length)throw new Error(JSON.stringify({mobileOverflow,errors}));
if(state.slotHighlight!=='shaded-teal-wall-depth')throw new Error('Current shaded wall treatment missing');
const result={headerInFlow,slotHighlight:state.slotHighlight,samples,range,hoverDegrees:afterHover-beforeHover,pageScrolledOverCanvas:afterWheel-beforeWheel,mobileOverflow,reducedMotionKeyboardDegrees:keyboardAfter-keyboardBefore,geometrySource:state.geometrySource,outletCount:state.outletCount,closedEnd:state.closedEnd,errors};
await writeFile(output+'/verification.json',JSON.stringify(result,null,2));
console.log(JSON.stringify(result,null,2));
await browser.close();
